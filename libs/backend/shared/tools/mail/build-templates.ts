import { readFile, writeFile } from 'node:fs/promises';

import mjml2html from 'mjml';
import { format, resolveConfig } from 'prettier';

async function build() {
  const root = 'libs/backend/shared/src/lib/mail';
  const templates: Record<string, string> = {};
  const brandSource = await readFile('assets/brand/public.json', 'utf8');
  const brand = JSON.parse(brandSource) as { emailLogo: string };
  const layoutSource = await readFile(`${root}/templates/layout.mjml`, 'utf8');
  const layout = layoutSource.replace('{{ logoUrl }}', `{{ origin }}/static/brand/${brand.emailLogo}`);

  for (const name of ['verification', 'security']) {
    const source = await readFile(`${root}/templates/${name}.mjml`, 'utf8');
    const document = layout
      .replace('<!-- preview -->', name === 'verification' ? 'Your verification code' : 'Account security')
      .replace('<!-- content -->', source);
    const result = await mjml2html(document, { validationLevel: 'strict', fonts: {}, ignoreIncludes: true });

    templates[name] = result.html;
  }
  const sourceOutput = `// Generated by backend-shared:emails-build. Do not edit directly.\nexport const templates = ${JSON.stringify(templates, null, 2)} as const;\n`;
  const target = `${root}/templates.generated.ts`;
  const config = await resolveConfig(target);
  const output = await format(sourceOutput, { ...config, filepath: target });

  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8');

    if (current !== output) {
      throw new Error('email_templates_stale');
    }
  } else {
    await writeFile(target, output);
  }
}
void build();
