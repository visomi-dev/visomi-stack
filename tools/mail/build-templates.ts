import { readFile, writeFile } from 'node:fs/promises';

import mjml2html from 'mjml';
import { format, resolveConfig } from 'prettier';

async function build() {
  const root = 'apps/web/api/src/auth/mail';
  const templates: Record<string, string> = {};

  for (const name of ['verification', 'security']) {
    const source = await readFile(`${root}/templates/${name}.mjml`, 'utf8');
    const result = await mjml2html(source, { validationLevel: 'strict', fonts: {}, ignoreIncludes: true });

    templates[name] = result.html;
  }
  const sourceOutput = `// Generated by web-api:emails-build. Do not edit directly.\nexport const templates = ${JSON.stringify(templates, null, 2)} as const;\n`;
  const target = `${root}/templates.generated.ts`;
  const config = await resolveConfig(target);
  const output = await format(sourceOutput, { ...config, filepath: target });

  if (process.argv.includes('--check')) {
    const current = await readFile(target, 'utf8');

    if (current !== output) {
      throw new Error('email_templates_stale');
    }
  } else {
    await writeFile(target, output);
  }
}
void build();
